//! System volume: `IMMDeviceEnumerator` -> `GetDefaultAudioEndpoint(eRender, eConsole)` ->
//! `IAudioEndpointVolume`, with `IAudioEndpointVolumeCallback` callback (level/mute change) and
//! `IMMNotificationClient` (default device change).
//!
//! THREADING: `AudioController` lives and is used ONLY by the shell thread (COM STA). The COM callbacks
//! may arrive from arbitrary threads: they do NOT touch the controller state, they only
//! `PostMessageW(ui_hwnd, WM_DOCK_VOLUME, level, muted)` (volume change) or
//! `PostThreadMessageW(shell_tid, WM_SHELL_AUDIO_DEVICE_CHANGED)` (device change);
//! the shell thread then calls `reopen_endpoint()` and posts WM_DOCK_VOLUME.
//! Shutdown: `Unregister*Notify` BEFORE releasing the endpoint.

