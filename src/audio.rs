/// Endpoint id (`GetId`), COM string freed.
fn device_id(dev: &IMMDevice) -> Option<String> {
    // SAFETY: `dev` is valid.
    let p = match unsafe { dev.GetId() } {
        Ok(p) => p,
        Err(e) => {
            log!("audio: GetId failed: {e}");
            return None;
        }
    };
    if p.is_null() {
        return None;
    }
    // SAFETY: NUL-terminated wide string returned by GetId, read once and then freed.
    let s = unsafe { p.to_string() }.ok();
    // SAFETY: allocated by COM (CoTaskMemAlloc), not used after this line.
    unsafe { CoTaskMemFree(Some(p.0 as *const core::ffi::c_void)) };
    s
}

/// `PKEY_Device_FriendlyName` of the endpoint.
fn friendly_name(dev: &IMMDevice) -> Option<String> {
    // SAFETY: `dev` is valid.
    let store = unsafe { dev.OpenPropertyStore(STGM_READ) }.ok()?;
    // SAFETY: `store` is valid, key is valid.
    let mut pv = unsafe { store.GetValue(&PKEY_Device_FriendlyName) }.ok()?;
    // SAFETY: `pv` is a PROPVARIANT initialized by GetValue.
    let r = unsafe { PropVariantToStringAlloc(&pv) };
    let name = match r {
        Ok(p) if !p.is_null() => {
            // SAFETY: NUL-terminated wide string allocated by COM, read and then freed.
            let s = unsafe { p.to_string() }.ok();
            // SAFETY: same pointer, not used anymore.
            unsafe { CoTaskMemFree(Some(p.0 as *const core::ffi::c_void)) };
            s
        }
        Ok(_) => None,
        Err(e) => {
            log!("audio: device name unreadable: {e}");
            None
        }
    };
    // SAFETY: `pv` belongs to us and is no longer used.
    let _ = unsafe { PropVariantClear(&mut pv) };
    name.map(|s| s.trim().to_string()).filter(|s| !s.is_empty())
}

/// Form factor of the endpoint (`PKEY_AudioEndpoint_FormFactor`, VT_UI4); `Speaker` if unreadable.
fn device_kind(dev: &IMMDevice) -> DeviceKind {
    // SAFETY: `dev` is valid.
    let Ok(store) = (unsafe { dev.OpenPropertyStore(STGM_READ) }) else { return DeviceKind::Speaker };
    // SAFETY: `store` is valid, key is valid.
    let Ok(mut pv) = (unsafe { store.GetValue(&PKEY_AudioEndpoint_FormFactor) }) else { return DeviceKind::Speaker };
    // SAFETY: `pv` is a PROPVARIANT initialized by GetValue (conversion fails on VT_EMPTY, handled).
    let kind = unsafe { PropVariantToUInt32(&pv) }.map(DeviceKind::from_form_factor).unwrap_or(DeviceKind::Speaker);
    // SAFETY: `pv` belongs to us and is no longer used.
    let _ = unsafe { PropVariantClear(&mut pv) };
    kind
}

// ------------------------------------------------- COM callbacks (arbitrary threads)

/// `IAudioEndpointVolumeCallback`: may arrive from any thread. Does not touch the controller:
/// decodes the payload and posts `WM_DOCK_VOLUME` to the UI.
#[implement(IAudioEndpointVolumeCallback)]
struct VolumeWatch {
    ui_hwnd: isize,
}

impl IAudioEndpointVolumeCallback_Impl for VolumeWatch_Impl {
    fn OnNotify(&self, pnotify: *mut AUDIO_VOLUME_NOTIFICATION_DATA) -> WinResult<()> {
        // SAFETY: WASAPI passes a pointer valid for the duration of the callback (or null,
        // handled by `as_ref`); only scalar fields are read.
        if let Some(d) = unsafe { pnotify.as_ref() } {
            let level = (d.fMasterVolume.clamp(0.0, 1.0) * 100.0).round() as u8;
            post_volume(self.ui_hwnd, VolumeState { level, muted: d.bMuted.as_bool(), available: true });
        }
        Ok(())
    }
}

/// `IMMNotificationClient`: tells the shell thread that the default device changed
/// (or that a device appeared/disappeared/changed state); the shell thread will do the reopening.
#[implement(IMMNotificationClient)]
struct DeviceWatch;

fn wake_shell() {
    let tid = crate::shell_thread::thread_id();
    if tid != 0 {
        // SAFETY: PostThreadMessageW is thread-safe; it only fails if the thread no longer exists.
        let _ = unsafe { PostThreadMessageW(tid, WM_SHELL_AUDIO_DEVICE_CHANGED, WPARAM(0), LPARAM(0)) };
    }
}

impl IMMNotificationClient_Impl for DeviceWatch_Impl {
    fn OnDeviceStateChanged(&self, _id: &PCWSTR, _state: DEVICE_STATE) -> WinResult<()> {
        wake_shell();
        Ok(())
    }
    fn OnDeviceAdded(&self, _id: &PCWSTR) -> WinResult<()> {
        wake_shell();
        Ok(())
    }
    fn OnDeviceRemoved(&self, _id: &PCWSTR) -> WinResult<()> {
        wake_shell();
        Ok(())
    }
    fn OnDefaultDeviceChanged(&self, flow: EDataFlow, role: ERole, _id: &PCWSTR) -> WinResult<()> {
        if flow == eRender && role == eConsole {
            wake_shell();
        }
        Ok(())
    }
    fn OnPropertyValueChanged(&self, _id: &PCWSTR, _key: &PROPERTYKEY) -> WinResult<()> {
        Ok(())
    }
}

// ------------------------------------------------- controller

/// Owns the enumerator, the current endpoint and the callback registrations.
/// Private fields; created with `new` on the shell thread.
pub struct AudioController {
    ui_hwnd: isize,
    state: VolumeState,
    enumerator: IMMDeviceEnumerator,
    device_cb: IMMNotificationClient,
    endpoint: Option<IAudioEndpointVolume>,
    volume_cb: Option<IAudioEndpointVolumeCallback>,
}

impl AudioController {
    /// Creates the enumerator, registers `IMMNotificationClient`, opens the default endpoint and
    /// registers its volume callback. If there is no device it still returns `Ok`
    /// with `state().available == false`. `Err` only if COM/the enumerator are not available.
    /// `ui_hwnd` is the HWND to post `WM_DOCK_VOLUME` to. Shell thread, COM STA.
    pub fn new(ui_hwnd: HWND) -> Result<AudioController, String> {
        // SAFETY: COM is initialized on the shell thread (STA) before this call.
        let enumerator: IMMDeviceEnumerator = unsafe { CoCreateInstance(&MMDeviceEnumerator, None, CLSCTX_ALL) }
            .map_err(|e| format!("MMDeviceEnumerator: {e}"))?;
        let device_cb: IMMNotificationClient = DeviceWatch.into();
        // SAFETY: `device_cb` is a valid COM object; it stays registered until we
        // unregister it in `shutdown`.
        unsafe { enumerator.RegisterEndpointNotificationCallback(&device_cb) }
            .map_err(|e| format!("RegisterEndpointNotificationCallback: {e}"))?;
        let mut c = AudioController {
            ui_hwnd: ui_hwnd.0 as isize,
            state: VolumeState::default(),
            enumerator,
            device_cb,
            endpoint: None,
            volume_cb: None,
        };
        c.open_endpoint();
        c.refresh();
        log!("audio: controller ready, state {:?}", c.state);
        Ok(c)
    }

    /// Releases the current endpoint (unregistering the callback first).
    fn close_endpoint(&mut self) {
        if let (Some(ep), Some(cb)) = (self.endpoint.as_ref(), self.volume_cb.as_ref()) {
            // SAFETY: `cb` is the one registered on `ep`; it is unregistered before release.
            let _ = unsafe { ep.UnregisterControlChangeNotify(cb) };
        }
        self.volume_cb = None;
        self.endpoint = None;
    }

    /// Opens the default render endpoint and registers the callback. Without a device
    /// it leaves `endpoint == None`.
    fn open_endpoint(&mut self) {
        self.close_endpoint();
        // SAFETY: `enumerator` is valid; the results are COM smart pointers managed by windows-rs.
        let dev = match unsafe { self.enumerator.GetDefaultAudioEndpoint(eRender, eConsole) } {
            Ok(d) => d,
            Err(e) => {
                log!("audio: no default render endpoint: {e}");
                DEFAULT_IS_HEADPHONE.store(false, Ordering::Relaxed);
                return;
            }
        };
        DEFAULT_IS_HEADPHONE.store(device_kind(&dev).is_headphone(), Ordering::Relaxed);
        // SAFETY: Activate with IAudioEndpointVolume (CLSCTX_ALL, no activation parameter).
        let ep: IAudioEndpointVolume = match unsafe { dev.Activate(CLSCTX_ALL, None) } {
            Ok(e) => e,
            Err(e) => {
                log!("audio: Activate(IAudioEndpointVolume) failed: {e}");
                return;
            }
        };
        let cb: IAudioEndpointVolumeCallback = VolumeWatch { ui_hwnd: self.ui_hwnd }.into();
        // SAFETY: `cb` is valid, unregistered in `close_endpoint` before `ep` is released.
        match unsafe { ep.RegisterControlChangeNotify(&cb) } {
            Ok(()) => self.volume_cb = Some(cb),
            Err(e) => log!("audio: RegisterControlChangeNotify failed: {e}"),
        }
        self.endpoint = Some(ep);
    }

    /// Re-reads level and mute from the endpoint (`GetMasterVolumeLevelScalar` / `GetMute`),
    /// updates the state and returns it.
    pub fn refresh(&mut self) -> VolumeState {
        self.state = match self.endpoint.as_ref() {
            None => VolumeState::default(),
            Some(ep) => {
                // SAFETY: `ep` is a valid endpoint owned by this controller.
                let lvl = unsafe { ep.GetMasterVolumeLevelScalar() };
                // SAFETY: same.
                let mute = unsafe { ep.GetMute() };
                match (lvl, mute) {
                    (Ok(l), Ok(m)) => VolumeState {
                        level: (l.clamp(0.0, 1.0) * 100.0).round() as u8,
                        muted: m.as_bool(),
                        available: true,
                    },
                    // Device gone: "not available" state; the device callback
                    // will trigger a reopen.
                    _ => VolumeState::default(),
                }
            }
        };
        self.state
    }

    /// Changes the volume by `delta_percent` points (negative = down), clamped 0..=100, with
    /// `SetMasterVolumeLevelScalar`; if the result is > 0 it clears mute. Returns the new state.
    pub fn adjust(&mut self, delta_percent: i32) -> VolumeState {
        let cur = self.refresh();
        let Some(ep) = self.endpoint.as_ref() else { return cur };
        let target = (cur.level as i32 + delta_percent).clamp(0, 100);
        // SAFETY: `ep` is valid; the context GUID lives for the whole call.
        if let Err(e) = unsafe { ep.SetMasterVolumeLevelScalar(target as f32 / 100.0, &MY_CONTEXT) } {
            log!("audio: SetMasterVolumeLevelScalar failed: {e}");
        }
        if target > 0 && cur.muted {
            // SAFETY: same.
            if let Err(e) = unsafe { ep.SetMute(false, &MY_CONTEXT) } {
                log!("audio: SetMute(false) failed: {e}");
            }
        }
        self.refresh()
    }

    /// Toggles mute (`SetMute`). Returns the new state.
    pub fn toggle_mute(&mut self) -> VolumeState {
        let cur = self.refresh();
        let Some(ep) = self.endpoint.as_ref() else { return cur };
        // SAFETY: `ep` is valid; the context GUID lives for the whole call.
        if let Err(e) = unsafe { ep.SetMute(!cur.muted, &MY_CONTEXT) } {
            log!("audio: SetMute failed: {e}");
        }
        self.refresh()
    }

    /// Sets the master volume to `percent` (0..=100) with `SetMasterVolumeLevelScalar`; if > 0 clears
    /// mute. Returns the new state. Used by the audio popup slider.
    pub fn set_level(&mut self, percent: u8) -> VolumeState {
        let cur = self.refresh();
        let Some(ep) = self.endpoint.as_ref() else { return cur };
        let target = percent.min(100);
        // SAFETY: `ep` is valid; the context GUID lives for the whole call.
        if let Err(e) = unsafe { ep.SetMasterVolumeLevelScalar(target as f32 / 100.0, &MY_CONTEXT) } {
            log!("audio: SetMasterVolumeLevelScalar({target}) failed: {e}");
        }
        if target > 0 && cur.muted {
            // SAFETY: same.
            if let Err(e) = unsafe { ep.SetMute(false, &MY_CONTEXT) } {
                log!("audio: SetMute(false) failed: {e}");
            }
        }
        self.refresh()
    }

    /// ACTIVE output devices (`EnumAudioEndpoints(eRender, DEVICE_STATE_ACTIVE)`), in the order
    /// of the enumerator, with the default one marked. Empty if the enumeration fails (logged).
    pub fn list_outputs(&self) -> Vec<OutputDevice> {
        // SAFETY: `enumerator` is valid, owned by the controller (shell thread, COM STA).
        let coll = match unsafe { self.enumerator.EnumAudioEndpoints(eRender, DEVICE_STATE_ACTIVE) } {
            Ok(c) => c,
            Err(e) => {
                log!("audio: EnumAudioEndpoints failed: {e}");
                return Vec::new();
            }
        };
        // SAFETY: `coll` is valid.
        let n = match unsafe { coll.GetCount() } {
            Ok(n) => n,
            Err(e) => {
                log!("audio: GetCount failed: {e}");
                return Vec::new();
            }
        };
        // SAFETY: `enumerator` is valid; no default = None (no check mark).
        let default_id =
            unsafe { self.enumerator.GetDefaultAudioEndpoint(eRender, eConsole) }.ok().and_then(|d| device_id(&d));
        let mut out = Vec::with_capacity(n as usize);
        for i in 0..n {
            // SAFETY: `i < n`, `coll` is valid.
            let dev = match unsafe { coll.Item(i) } {
                Ok(d) => d,
                Err(e) => {
                    log!("audio: Item({i}) failed: {e}");
                    continue;
                }
            };
            let Some(id) = device_id(&dev) else { continue };
            let name = friendly_name(&dev).unwrap_or_else(|| id.clone());
            let is_default = default_id.as_deref() == Some(id.as_str());
            let kind = device_kind(&dev);
            out.push(OutputDevice { id, name, is_default, kind });
        }
        out
    }

    /// Makes `id` the default device for all three roles (`IPolicyConfig::SetDefaultEndpoint`,
    /// undocumented interface). The change then arrives via `OnDefaultDeviceChanged` ->
    /// `reopen_endpoint` as for a change made from Settings.
    pub fn set_default_output(&mut self, id: &str) -> Result<(), String> {
        // SAFETY: COM STA initialized on the shell thread; the CLSID matches PolicyConfigClient.
        let pc: IPolicyConfig = unsafe { CoCreateInstance(&CLSID_POLICY_CONFIG_CLIENT, None, CLSCTX_ALL) }
            .map_err(|e| format!("PolicyConfigClient: {e}"))?;
        let wid: Vec<u16> = id.encode_utf16().chain(std::iter::once(0)).collect();
        for role in [eConsole, eMultimedia, eCommunications] {
            // SAFETY: `wid` is NUL-terminated and lives for the call; `pc` is valid.
            unsafe { pc.SetDefaultEndpoint(PCWSTR(wid.as_ptr()), role) }
                .ok()
                .map_err(|e| format!("SetDefaultEndpoint(role {}): {e}", role.0))?;
        }
        log!("audio: default device set");
        Ok(())
    }

    /// Default device changed: releases the callback on the old endpoint, opens the
    /// new one, registers the callback and re-reads the state. Returns the new state.
    pub fn reopen_endpoint(&mut self) -> VolumeState {
        self.open_endpoint();
        self.refresh()
    }

    /// Unregisters the callbacks and releases everything. To be called on the shell thread
    /// before `CoUninitialize`.
    pub fn shutdown(mut self) {
        self.close_endpoint();
        // SAFETY: `device_cb` is the one registered in `new`.
        let _ = unsafe { self.enumerator.UnregisterEndpointNotificationCallback(&self.device_cb) };
        log!("audio: controller closed");
    }
}

// ------------------------------------------------- encoding of WM_DOCK_VOLUME

/// Encodes `st` into the parameters of `WM_DOCK_VOLUME` (wParam = level, lParam = 1 muted / 0 not
/// muted / -1 no device) and posts them to the UI window. Thread-safe: can be called from
/// COM callbacks on arbitrary threads and from the shell thread.
pub fn post_volume(ui_hwnd: isize, st: VolumeState) {
    use windows::Win32::UI::WindowsAndMessaging::PostMessageW;
    let lp: isize = if !st.available {
        -1
    } else if st.muted {
        1
    } else {
        0
    };
    let hwnd = HWND(ui_hwnd as *mut core::ffi::c_void);
    // SAFETY: PostMessageW is thread-safe; if the window no longer exists it only fails.
    let _ = unsafe { PostMessageW(Some(hwnd), crate::msg::WM_DOCK_VOLUME, WPARAM(st.level as usize), LPARAM(lp)) };
}

/// Inverse of `post_volume`: rebuilds the state from the `WM_DOCK_VOLUME` parameters.
pub fn decode_volume_msg(wparam: usize, lparam: isize) -> VolumeState {
    if lparam < 0 {
        return VolumeState::default();
    }
    VolumeState { level: wparam.min(100) as u8, muted: lparam != 0, available: true }
}
